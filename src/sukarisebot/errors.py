"""Исключения SDK.

Каждая ошибка, которую создаёт сам SDK, наследует :class:`SukaRiseError`, поэтому
один ``except SukaRiseError`` ловит их все. Иерархия::

    SukaRiseError
    ├── ConnectionRefused   сервер не пустил бота или оборвал сессию насовсем
    ├── ResponseError       сервер отказал в конкретном запросе
    ├── RequestTimeout      сервер не ответил на запрос вовремя
    ├── NotConnected        действие вне подключённого бота
    ├── ProtocolError       сервер прислал кадр, который SDK не может прочитать
    └── InvalidArgument     аргумент заведомо неверен (наследует и ``ValueError``)

Что делать с каждой ошибкой, описано в ``docs/errors.md``.
"""


class SukaRiseError(Exception):
    """Базовый класс всех ошибок SDK.

    Ловите его, когда нужно обработать любую ошибку бота разом. Ошибки самого
    Python (``TypeError``, ``KeyError`` и т. п.) сюда не входят: они означают
    ошибку в коде бота, а не сбой связи или отказ сервера.
    """


class ConnectionRefused(SukaRiseError):
    """Сервер не принял подключение или навсегда оборвал сессию.

    Исключение выходит из :meth:`Bot.run` и :meth:`Bot.start`, когда бот
    остановился и дальше работать не может: токен отозван, комната недоступна,
    бот запущен из другого места.

    Если ``do_not_reconnect`` равен ``False``, отказ временный (например, у
    владельца закончился PREMIUM или комната ещё не готова). Бот с
    ``reconnect=True`` в этом случае не завершается, а повторяет попытку сам;
    исключение с ``do_not_reconnect=False`` вы увидите только при
    ``reconnect=False``.

    :ivar message: текст отказа так, как его прислал сервер.
    :ivar do_not_reconnect: ``True`` — повтор ничего не изменит, ``False`` — стоит
        попробовать позже.
    """

    def __init__(self, message: str, do_not_reconnect: bool = True) -> None:
        """Создать исключение.

        :param message: текст отказа.
        :param do_not_reconnect: слово сервера, стоит ли пробовать снова.
        """
        super().__init__(message)
        self.message = message
        """Текст отказа так, как его прислал сервер (по-английски)."""
        self.do_not_reconnect = do_not_reconnect
        """``True``: повтор ничего не изменит. ``False``: отказ временный."""


class ResponseError(SukaRiseError):
    """Сервер отказал в одном запросе; соединение при этом остаётся рабочим.

    Типичные причины: у бота нет прав модератора, пользователя нет в комнате,
    запрос не поддерживается сервером, превышен лимит частоты.

    :ivar message: текст отказа так, как его прислал сервер (по-английски).
    """

    def __init__(self, message: str) -> None:
        """Создать исключение.

        :param message: текст отказа сервера.
        """
        super().__init__(message)
        self.message = message
        """Текст отказа так, как его прислал сервер (по-английски)."""


class RequestTimeout(SukaRiseError):
    """Сервер не ответил на запрос за отведённое время (10 секунд по умолчанию).

    Запрос мог всё же дойти и выполниться: ответа просто не пришло. Если действие
    нельзя повторять вслепую (чаевые, покупка), сначала проверьте результат, например
    через :meth:`BotAPI.gold`.
    """


class NotConnected(SukaRiseError):
    """Действие вызвано, когда у бота нет живого соединения.

    Возникает при обращении к ``bot.api`` вне работающего бота, при запросе
    во время переподключения и при обрыве связи посреди запроса.
    """


class ProtocolError(SukaRiseError):
    """Сервер прислал кадр, который SDK не умеет читать.

    Одиночный непонятный кадр SDK пропускает и пишет предупреждение в журнал.
    Исключение доходит до вашего кода только в редких случаях: например,
    сервер не начал разговор с ``SessionMetadata``.
    """


class InvalidArgument(SukaRiseError, ValueError):
    """Аргумент заведомо неверен, поэтому запрос не отправлялся вовсе.

    SDK проверяет аргументы до отправки: пустой текст, неизвестную реакцию,
    координату вне допустимого диапазона, наряд без части тела. Ошибка
    возникает в той строке вашего кода, где сделана ошибка, а не отказом сервера
    позже. Наследует и :class:`ValueError`, поэтому ловится и им.
    """
